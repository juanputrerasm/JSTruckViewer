/*
  4x4 Evolution truck manifests: TRK version 6 (Evo 1) and version 7 (Evo 2).

  The container changed - Evo ships trucks in POD2, not POD1 - but the manifest itself is
  the same line-oriented label/value text MTM2 uses, with a version header instead of an
  "MTM2" one:

    version
    6                      6 = 4x4 Evolution, 7 = 4x4 Evolution 2
    truckName
    Chevrolet Blazer TrailBlazer 4WD
    ...
    signature: C89BC44E D3A8FB4D // WARNING: Do not edit this file

  Three things separate it from the MTM2 dialect the sibling parser reads:

    - Wheel anchors are ONE vec3 line ("faxle.rtire.static_bpos" -> "+2.385,-0.700,+5.360")
      rather than three ".x"/".y"/".z" label/value pairs.
    - Models are .SMF, not .BIN, and the manifest names bare stems ("trblaz", "TrailBlazer").
    - Several fields are counted lists: a "<label>[]" line is followed by N bare value lines
      with no label of their own. Where the count lives in an earlier field it is used;
      "sc[].pt" has no count anywhere, so its run is read until a line stops looking like a
      vec3. That is safe because every label that can follow it is non-numeric.

  Verified across every TRK in both stock TRUCK.PODs: 121 v6 files and 150 v7 files, all
  read to their signature line with no unconsumed list values.

  Evo has no axle model, axle bars, driveshaft or instrument cluster - axleModelName is
  "NULL.BIN" and barTextureName "NULL.RAW" in all 271 stock manifests - so the assembly is
  body plus four tires plus lights, and those parts are skipped rather than reported missing.
*/

const EVO_VERSIONS = { 6: "EVO1", 7: "EVO2" };

// Counted lists whose length is carried by an earlier scalar field.
const COUNTED_LISTS = {
  "xm.gear_ratio[]": "xm.maxGear",
  "xm.gearInertia[]": "xm.maxGear",
  "eng.torqueTable[]": "eng.torqueTableCount",
  "stockPartList[]": "numStockParts",
  "colorList[]": "numColors"
};

const WHEEL_ANCHOR_KEYS = new Set([
  "faxle.rtire.static_bpos",
  "faxle.ltire.static_bpos",
  "raxle.rtire.static_bpos",
  "raxle.ltire.static_bpos"
]);

const STRING_SPEC_FIELDS = new Set([
  "truckMake",
  "truckModel",
  "truckClass",
  "teamRequirement"
]);

const NAMED_STRING_FIELDS = new Set([
  "truckModelBaseName",
  "tireModelBaseName",
  "axleModelName",
  "shockTextureName",
  "barTextureName"
]);

/** True when these lines are an Evo manifest rather than an MTM1/MTM2 one. */
export function isEvoManifest(lines) {
  return (lines[0] ?? "").trim().toLowerCase() === "version"
    && Number.parseInt(lines[1] ?? "", 10) in EVO_VERSIONS;
}

export function parseEvoManifest(lines) {
  const version = Number.parseInt(lines[1] ?? "", 10);
  const manifest = {
    formatVersion: EVO_VERSIONS[version],
    trkVersion: version,
    modelExtension: ".SMF",
    truckName: "",
    truckModelBaseName: "",
    tireModelBaseName: "",
    axleModelName: "",
    shockTextureName: undefined,
    barTextureName: undefined,
    axlebarOffset: undefined,
    superiorAxlebarOffset: undefined,
    driveshaftPos: undefined,
    wheelAnchors: {},
    scrapePoints: [],
    instrumentCluster: undefined,
    waveFiles: [],
    numberOfLights: undefined,
    lights: [],
    colors: [],
    stockParts: [],
    specs: {},
    signature: "",
    unknownFields: {}
  };

  for (let i = 2; i < lines.length; i += 1) {
    const label = lines[i];
    if (label.startsWith("signature:")) {
      manifest.signature = label.slice("signature:".length).split("//")[0].trim();
      continue;
    }

    // "sc[].pt" is the scrape-point run. It carries no count, so it is read while the lines
    // still parse as three numbers.
    if (label === "sc[].pt") {
      while (i + 1 < lines.length && isVec3Line(lines[i + 1])) {
        manifest.scrapePoints.push(parseVec3(lines[i + 1]));
        i += 1;
      }
      continue;
    }

    // "xm.gear_ratio[]" is the one list label that carries a trailing gear-name comment, and
    // the comment changes with the gear count ("... 1st/2nd/3rd" through "... 4th/5th"), so
    // the lookup uses everything up to the "[]" rather than the whole line.
    const listLabel = label.includes("[]") ? label.slice(0, label.indexOf("[]") + 2) : label;
    const countField = COUNTED_LISTS[listLabel];
    if (countField) {
      const count = Math.max(0, Math.trunc(Number(manifest.specs[countField]) || 0));
      const values = lines.slice(i + 1, i + 1 + count);
      i += values.length;
      if (listLabel === "colorList[]") {
        manifest.colors = values.map(parseColorEntry);
      } else if (listLabel === "stockPartList[]") {
        manifest.stockParts = values.map((value) => value.trim());
      } else {
        // Stored under the canonical "<name>[]" key so the gear-name comment does not leak
        // into the field name.
        manifest.specs[listLabel] = values.map((value) => Number.parseFloat(value) || 0);
      }
      continue;
    }

    const value = lines[i + 1] ?? "";

    if (label === "Wave File") {
      manifest.waveFiles.push(value);
      i += 1;
      while (i + 1 < lines.length && isWaveFileLine(lines[i + 1])) {
        manifest.waveFiles.push(lines[i + 1]);
        i += 1;
      }
      continue;
    }

    if (WHEEL_ANCHOR_KEYS.has(label)) {
      manifest.wheelAnchors[label] = parseVec3(value);
      i += 1;
      continue;
    }

    if (label === "truckName") {
      manifest.truckName = value;
      i += 1;
      continue;
    }
    if (NAMED_STRING_FIELDS.has(label)) {
      manifest[label] = value;
      i += 1;
      continue;
    }
    if (label === "axlebarOffset" || label === "driveshaftPos") {
      manifest[label] = parseVec3(value);
      i += 1;
      continue;
    }
    if (label === "Instrument Cluster") {
      manifest.instrumentCluster = value;
      i += 1;
      continue;
    }
    if (label === "Number of Lights") {
      manifest.numberOfLights = Number.parseInt(value, 10) || 0;
      i += 1;
      continue;
    }

    const lightMatch = label.match(/^Light (\d+) /);
    if (lightMatch) {
      applyLightField(manifest, Number.parseInt(lightMatch[1], 10), label.slice(lightMatch[0].length).trim(), value);
      i += 1;
      continue;
    }

    manifest.specs[label] = STRING_SPEC_FIELDS.has(label) ? value : parseSpecValue(value);
    i += 1;
  }

  manifest.lights = manifest.lights.filter(Boolean);
  return manifest;
}

function applyLightField(manifest, index, property, value) {
  while (manifest.lights.length <= index) manifest.lights.push(null);
  if (!manifest.lights[index]) manifest.lights[index] = { index };
  const light = manifest.lights[index];
  const parts = value.split(",");
  if (property === "type") {
    light.type = Number.parseInt(value, 10) || 0;
  } else if (property.startsWith("body axis pos")) {
    light.pos = { x: number(parts[0]), y: number(parts[1]), z: number(parts[2]) };
    light.bitmapRadius = number(parts[3]);
  } else if (property.startsWith("heading")) {
    light.heading = number(parts[0]);
    light.pitch = number(parts[1]);
    light.spinSpeed = number(parts[2]);
  } else if (property.startsWith("cone:")) {
    light.coneLength = number(parts[0]);
    light.coneBaseRadius = number(parts[1]);
    light.coneRimRadius = number(parts[2]);
    light.coneTexture = (parts[3] ?? "").trim();
  } else if (property.startsWith("source:")) {
    light.sourceBitmap = value.trim();
  } else if (property.startsWith("ms on")) {
    light.msOn = Number.parseInt(parts[0], 10) || 0;
    light.msOff = Number.parseInt(parts[1], 10) || 0;
  }
}

/*
  A paint scheme: three HSV shift components, the RGB swatch the garage shows for them, and
  a decal texture name. Every stock entry names "NULL" for that texture, so the viewer only
  reports the swatch rather than compositing a decal it has never seen a real example of.
*/
function parseColorEntry(line) {
  const parts = line.split(",");
  return {
    hue: number(parts[0]),
    saturation: number(parts[1]),
    brightness: number(parts[2]),
    red: Math.round(number(parts[3])),
    green: Math.round(number(parts[4])),
    blue: Math.round(number(parts[5])),
    textureName: (parts[6] ?? "").trim()
  };
}

// The Wave File run is the one list whose length is neither counted nor bounded by a value
// shape, so it ends at the first line that is not a sound file name.
function isWaveFileLine(line) {
  return /\.wav$/i.test(line.trim());
}

function isVec3Line(line) {
  const parts = line.split(",");
  return parts.length === 3 && parts.every((part) => Number.isFinite(Number.parseFloat(part)));
}

function parseVec3(value) {
  const parts = String(value).split(",");
  return { x: number(parts[0]), y: number(parts[1]), z: number(parts[2]) };
}

// Scalars stay numbers, comma-separated tuples become number arrays, and anything else is
// kept as text so an unrecognized field survives into the summary intact.
function parseSpecValue(value) {
  const trimmed = value.trim();
  if (trimmed === "") return "";
  const parts = trimmed.split(",");
  if (parts.every((part) => /^[+-]?(\d+\.?\d*|\.\d+)([eE][+-]?\d+)?$/.test(part.trim()))) {
    return parts.length === 1 ? Number.parseFloat(parts[0]) : parts.map((part) => Number.parseFloat(part));
  }
  return trimmed;
}

function number(value) {
  const parsed = Number.parseFloat((value ?? "").trim());
  return Number.isFinite(parsed) ? parsed : 0;
}
